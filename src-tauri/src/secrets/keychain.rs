/*!
# Keychain Secrets Module

**SECURITY CONSTRAINT**: This module interacts with the OS keychain to store and retrieve plaintext secrets (passwords, passphrases, etc).
Per the `ssh-secrets-security-checklist`, NO secret value should ever appear in a log line, an error message, or Debug output.
Errors generated by this module MUST NOT include the raw secret, and MUST NOT include memory dumps or unredacted context that could leak the secret.
Any struct holding a decrypted secret from this module must implement `Zeroize` and avoid deriving `Debug` (or implement a redacted `Debug` manually).
*/

use keyring::Entry;
use thiserror::Error;

#[derive(Debug, Error)]
pub enum KeychainError {
    #[error("Failed to access keychain entry")]
    AccessFailed,
    
    #[error("Secret not found for the given reference ID")]
    NotFound,
    
    #[error("Failed to store secret in the keychain")]
    StoreFailed,
    
    #[error("Failed to delete secret from the keychain")]
    DeleteFailed,
}

const SERVICE_NAME: &str = "server-command-center";

/// Stores a secret in the OS keychain.
/// `ref_id` should be a namespaced string (e.g. "scc:credential:<uuid>") to avoid collisions.
pub fn store_secret(ref_id: &str, secret: &str) -> Result<(), KeychainError> {
    let entry = Entry::new(SERVICE_NAME, ref_id)
        .map_err(|_| KeychainError::AccessFailed)?;
        
    entry.set_password(secret)
        .map_err(|_| KeychainError::StoreFailed)?;
        
    Ok(())
}

/// Retrieves a secret from the OS keychain.
/// The returned String should be zeroized after use by the caller.
pub fn read_secret(ref_id: &str) -> Result<String, KeychainError> {
    let entry = Entry::new(SERVICE_NAME, ref_id)
        .map_err(|_| KeychainError::AccessFailed)?;
        
    entry.get_password().map_err(|e| match e {
        keyring::Error::NoEntry => KeychainError::NotFound,
        _ => KeychainError::AccessFailed,
    })
}

/// Deletes a secret from the OS keychain.
pub fn delete_secret(ref_id: &str) -> Result<(), KeychainError> {
    let entry = Entry::new(SERVICE_NAME, ref_id)
        .map_err(|_| KeychainError::AccessFailed)?;
        
    entry.delete_credential().map_err(|e| match e {
        keyring::Error::NoEntry => KeychainError::NotFound,
        _ => KeychainError::DeleteFailed,
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use uuid::Uuid;

    #[test]
    fn test_keychain_crud() {
        let ref_id = format!("scc:test:{}", Uuid::new_v4());
        let secret = "super_secret_password_123";

        // Read before store should return NotFound or AccessFailed
        let missing = read_secret(&ref_id);
        assert!(missing.is_err());

        // Attempt to store
        store_secret(&ref_id, secret).expect("store_secret failed!");
        let retrieved = read_secret(&ref_id).expect("read_secret failed!");
        assert_eq!(retrieved, secret);
        delete_secret(&ref_id).expect("delete_secret failed!");
    }
}
